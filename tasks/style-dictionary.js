// Builds the design tokens in properties/ (see notes/design/tokens.md):
// - src/styles/variables.css: every token as a CSS custom property
// - src/styles/tokens.js: the canvas's mark.* colours as rgb triples
// - src/styles/tokens.json: every colour role resolved to rgba, with its
//   contrast requirement, for the contrast spec
import StyleDictionary from "style-dictionary";
import { converter, formatCss, formatRgb, parse } from "culori";

const CWD = process.cwd();
const COLOUR_ROLES = new Set([
	"surface",
	"prose",
	"chart",
	"annotation",
	"mark",
	"control",
	"art",
	"dev"
]);

const toOklch = converter("oklch");
const toRgb = converter("rgb");
const clamp01 = (n) => Math.min(1, Math.max(0, n));
// four places: enough to name an OKLCH lightness, and no float noise
const round4 = (n) => Math.round(n * 1e4) / 1e4;

const isColourRole = (token) => COLOUR_ROLES.has(token.path[0]);

const rgba = (value) => {
	const { r, g, b, alpha = 1 } = toRgb(parse(value));
	return [...[r, g, b].map((c) => Math.round(clamp01(c) * 255)), alpha];
};

// A role token's `modify`: `lighten` shifts OKLCH lightness (what the
// `oklch(from … calc(l ± n) c h)` hovers used to compute in place), `alpha`
// sets the opacity (what `color-mix(… transparent)` and rgba literals did).
const modify = (token) => {
	const { lighten, alpha } = token.modify;
	const colour = parse(token.value);
	if (lighten !== undefined) {
		const oklch = toOklch(colour);
		return formatCss({ ...oklch, l: round4(clamp01(oklch.l + lighten)) });
	}
	return formatRgb({ ...toRgb(colour), alpha });
};

const constName = (token) =>
	token.path.join("_").replace(/-/g, "_").toUpperCase();

const sd = new StyleDictionary({
	source: [`${CWD}/properties/**/*.json`],
	hooks: {
		transforms: {
			"color/modify": {
				type: "value",
				transitive: true,
				filter: (token) => token.modify !== undefined,
				transform: modify
			}
		},
		formats: {
			"javascript/mark-rgb": ({ dictionary }) =>
				[
					"// Do not edit directly, this file was auto-generated by npm run style.",
					"// The canvas's mark.* colours as [r, g, b] (canvas can't read CSS custom properties).",
					...dictionary.allTokens.map(
						(token) =>
							`export const ${constName(token)} = [${rgba(token.value).slice(0, 3).join(", ")}];`
					),
					""
				].join("\n"),
			"json/contrast": ({ dictionary }) =>
				JSON.stringify(
					Object.fromEntries(
						dictionary.allTokens.map((token) => [
							token.path.join("."),
							{
								css: `--${token.name}`,
								rgba: rgba(token.value),
								contrast: token.contrast ?? null
							}
						])
					),
					null,
					"\t"
				) + "\n"
		}
	},
	platforms: {
		css: {
			transformGroup: "css",
			transforms: ["color/modify"],
			buildPath: `${CWD}/src/styles/`,
			files: [
				{
					format: "css/variables",
					destination: "variables.css",
					options: {
						outputReferences: (token) => token.modify === undefined,
						formatting: { commentPosition: "above" }
					}
				}
			]
		},
		js: {
			transforms: ["name/kebab", "color/modify"],
			buildPath: `${CWD}/src/styles/`,
			files: [
				{
					format: "javascript/mark-rgb",
					destination: "tokens.js",
					filter: (token) => token.path[0] === "mark"
				},
				{
					format: "json/contrast",
					destination: "tokens.json",
					filter: isColourRole
				}
			]
		}
	}
});

await sd.buildAllPlatforms();
